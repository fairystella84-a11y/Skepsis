let lang = 'el';

export function setLang(l) {
  lang = STRINGS[l] ? l : 'el';
  document.documentElement.lang = lang;
}

export function getLang() {
  return lang;
}

export function t(key) {
  return STRINGS[lang][key] ?? STRINGS.el[key] ?? key;
}

// Pick the current-language field from a bilingual content object.
export function L(obj) {
  return obj ? obj[lang] ?? obj.el : '';
}

export function fmtDate(iso, opts = { day: 'numeric', month: 'short', year: 'numeric' }) {
  return new Date(iso).toLocaleDateString(lang === 'el' ? 'el-GR' : 'en-GB', opts);
}

export function fmtTime(iso) {
  return new Date(iso).toLocaleTimeString(lang === 'el' ? 'el-GR' : 'en-GB', { hour: '2-digit', minute: '2-digit', hourCycle: 'h23' });
}
